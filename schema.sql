-- 6. Add ESAT Access Permission Columns to Shared Profiles Table Safely (Locked by Default)
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='has_esat_access') THEN
        ALTER TABLE public.profiles ADD COLUMN has_esat_access BOOLEAN DEFAULT false;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='has_esat_diagnostic_access') THEN
        ALTER TABLE public.profiles ADD COLUMN has_esat_diagnostic_access BOOLEAN DEFAULT false;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='has_esat_topic_access') THEN
        ALTER TABLE public.profiles ADD COLUMN has_esat_topic_access BOOLEAN DEFAULT false;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='has_esat_mock_access') THEN
        ALTER TABLE public.profiles ADD COLUMN has_esat_mock_access BOOLEAN DEFAULT false;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='has_esat_fullmock_access') THEN
        ALTER TABLE public.profiles ADD COLUMN has_esat_fullmock_access BOOLEAN DEFAULT false;
    END IF;
END $$;

