-- 3. Create ESAT Question Bank Table (esat_questions)
CREATE TABLE IF NOT EXISTS public.esat_questions (
    id TEXT PRIMARY KEY,
    module_id TEXT REFERENCES public.esat_modules(id) ON DELETE RESTRICT,
    topic TEXT NOT NULL,
    subtopic TEXT,
    difficulty TEXT CHECK (difficulty IN ('Easy', 'Medium', 'Hard')) DEFAULT 'Medium',
    question TEXT NOT NULL,
    passage TEXT DEFAULT '',
    option_a TEXT NOT NULL,
    option_b TEXT NOT NULL,
    option_c TEXT NOT NULL,
    option_d TEXT NOT NULL,
    option_e TEXT NOT NULL,
    correct_answer INTEGER CHECK (correct_answer >= 0 AND correct_answer <= 4) NOT NULL,
    explanation TEXT DEFAULT '',
    explanation_status TEXT CHECK (explanation_status IN ('complete', 'missing', 'needs_review')) DEFAULT 'complete',
    source_file TEXT,
    source_page INTEGER,
    source_question_number INTEGER,
    is_verified BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_esat_questions_module ON public.esat_questions(module_id);
CREATE INDEX IF NOT EXISTS idx_esat_questions_topic ON public.esat_questions(topic);
CREATE INDEX IF NOT EXISTS idx_esat_questions_diff ON public.esat_questions(difficulty);

ALTER TABLE public.esat_questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public select from esat_questions" ON public.esat_questions;
CREATE POLICY "Allow public select from esat_questions" ON public.esat_questions FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow authenticated insert/update to esat_questions" ON public.esat_questions;
CREATE POLICY "Allow authenticated insert/update to esat_questions" ON public.esat_questions FOR ALL USING (true);


-- 4. Create ESAT Test Reports & Results Table (esat_report)
CREATE TABLE IF NOT EXISTS public.esat_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    test_title TEXT NOT NULL,
    test_type TEXT DEFAULT 'full_mock', -- 'full_mock', 'mock_test', 'diagnostic', 'topic_test'
    modules_taken TEXT[] DEFAULT ARRAY['Mathematics 1'],
    
    -- Overall Aggregate Metrics
    total_questions INTEGER NOT NULL DEFAULT 81,
    total_correct INTEGER NOT NULL DEFAULT 0,
    total_wrong INTEGER NOT NULL DEFAULT 0,
    total_unattempted INTEGER NOT NULL DEFAULT 0,
    overall_accuracy NUMERIC(5,2) DEFAULT 0.00,
    
    -- Module-wise Results JSON Array:
    -- [{"module": "Mathematics 1", "correct": 21, "total": 27, "wrong": 6, "unattempted": 0, "accuracy": 77.8, "esat_score": 6.8, "time_spent": "38:20"}, ...]
    module_scores_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    
    -- Topic-wise Breakdown JSON Array:
    -- [{"topic": "Algebra", "module": "Mathematics 1", "correct": 8, "total": 10, "pct": 80.0}, ...]
    topic_scores_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    
    -- Detailed Question-by-Question Review Logs
    answers_json JSONB DEFAULT '{}'::jsonb,
    details_json JSONB DEFAULT '[]'::jsonb,
    
    submit_time TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_esat_report_email ON public.esat_report(email);
CREATE INDEX IF NOT EXISTS idx_esat_report_test_type ON public.esat_report(test_type);
CREATE INDEX IF NOT EXISTS idx_esat_report_created_at ON public.esat_report(created_at DESC);

-- Enable RLS for esat_report
ALTER TABLE public.esat_report ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public insert to esat_report" ON public.esat_report;
CREATE POLICY "Allow public insert to esat_report" ON public.esat_report FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public select from esat_report" ON public.esat_report;
CREATE POLICY "Allow public select from esat_report" ON public.esat_report FOR SELECT USING (true);


