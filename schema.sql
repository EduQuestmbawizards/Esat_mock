-- 1. Create Student Registration Table (esat_user)
CREATE TABLE IF NOT EXISTS public.esat_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    target_course TEXT DEFAULT 'Engineering',
    selected_modules TEXT[] DEFAULT ARRAY['Mathematics 1', 'Mathematics 2', 'Physics'],
    topic TEXT DEFAULT 'ESAT Assessment',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_esat_user_email ON public.esat_user(email);

-- Enable RLS for esat_user
ALTER TABLE public.esat_user ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public insert to esat_user" ON public.esat_user;
CREATE POLICY "Allow public insert to esat_user" ON public.esat_user FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public select from esat_user" ON public.esat_user;
CREATE POLICY "Allow public select from esat_user" ON public.esat_user FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public update to esat_user" ON public.esat_user;
CREATE POLICY "Allow public update to esat_user" ON public.esat_user FOR UPDATE USING (true);


